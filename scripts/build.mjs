// Builds dist/: copies the static app, injects the service-worker precache list + version hash.
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const DIST = join(ROOT, 'dist');

rmSync(DIST, { recursive: true, force: true });
mkdirSync(DIST, { recursive: true });

for (const entry of ['index.html', 'manifest.webmanifest', 'sw.js', 'css', 'src', 'assets']) {
  const from = join(ROOT, entry);
  if (existsSync(from)) cpSync(from, join(DIST, entry), { recursive: true });
}

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

const files = walk(DIST)
  .map((f) => relative(DIST, f).split('\\').join('/'))
  .filter((f) => f !== 'sw.js')
  .sort();

const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(DIST, f)));
const version = hash.digest('hex').slice(0, 10);

// Update detection: the running page knows its own version (src/version.js, precached) and compares it with
// version.json fetched from the network (NOT precached; sw.js lets it bypass the cache).
writeFileSync(join(DIST, 'src/version.js'), `// Generated by scripts/build.mjs - do not edit.\nexport const BUILD_VERSION = ${JSON.stringify(version)};\n`);
// version.json also describes the published game (worlds with names, stages per world, question count, optional
// release notes) so players on an older build are told what the update adds (a new map/world, new stages...).
const { WORLDS, CONFIG } = await import(pathToFileURL(join(ROOT, 'src/config.js')).href);
const { QUESTIONS } = await import(pathToFileURL(join(ROOT, 'src/data/questions.js')).href);
const { t } = await import(pathToFileURL(join(ROOT, 'src/i18n/index.js')).href);
const { describeBuild } = await import(pathToFileURL(join(ROOT, 'src/game/release.js')).href);
let notes = null;
if (existsSync(join(ROOT, 'release-notes.json'))) notes = JSON.parse(readFileSync(join(ROOT, 'release-notes.json'), 'utf8'));
const release = describeBuild({
  worlds: WORLDS,
  levels: CONFIG.LEVELS_PER_WORLD,
  questions: Object.values(QUESTIONS).reduce((n, list) => n + list.length, 0),
  names: (id) => ({ ar: t('ar', `world.${id}`), en: t('en', `world.${id}`) }),
  notes,
});
writeFileSync(join(DIST, 'version.json'), `${JSON.stringify({ version, ...release })}\n`);

// Absolute site URL for Open Graph tags (share previews need absolute URLs).
// Set KQ_SITE_URL=https://example.com/path/ ; on GitHub Actions it is derived from GITHUB_REPOSITORY.
// index.html already carries DEFAULT_SITE_URL so the page works even when published WITHOUT a build
// (e.g. Pages "Deploy from a branch"); the build swaps it for KQ_SITE_URL / the GitHub repo URL when they differ.
const DEFAULT_SITE_URL = 'https://fxstrict.github.io/oddy/';
function siteUrl() {
  let url = process.env.KQ_SITE_URL || '';
  const repo = process.env.GITHUB_REPOSITORY;
  if (!url && repo) {
    const [owner, name] = repo.split('/');
    url = name.toLowerCase() === `${owner.toLowerCase()}.github.io` ? `https://${owner}.github.io/` : `https://${owner}.github.io/${name}/`;
  }
  if (!url) url = DEFAULT_SITE_URL;
  if (!url.endsWith('/')) url += '/';
  return url;
}
const SITE_URL = siteUrl();
const indexPath = join(DIST, 'index.html');
writeFileSync(indexPath, readFileSync(indexPath, 'utf8').replaceAll(DEFAULT_SITE_URL, SITE_URL));

const precache = ['./', ...files];
const swPath = join(DIST, 'sw.js');
let sw = readFileSync(swPath, 'utf8');
sw = sw.replace("'__VERSION__'", JSON.stringify(version)).replace('/*__PRECACHE__*/[]', JSON.stringify(precache));
writeFileSync(swPath, sw);
writeFileSync(join(DIST, '.nojekyll'), '');
// Search engines: robots.txt always; sitemap.xml only when the absolute site URL is known.
writeFileSync(join(DIST, 'robots.txt'), `User-agent: *\nAllow: /\n${SITE_URL ? `Sitemap: ${SITE_URL}sitemap.xml\n` : ''}`);
if (SITE_URL) {
  const today = new Date().toISOString().slice(0, 10);
  writeFileSync(join(DIST, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"><url><loc>${SITE_URL}</loc><lastmod>${today}</lastmod></url></urlset>\n`);
}
console.log(`build: dist/ ready (${files.length} files, version ${version}, site ${SITE_URL || 'n/a'})`);
